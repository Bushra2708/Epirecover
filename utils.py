@dataclass
class PipelineReport:
    """Original EpiQ report container — preserved for backward compatibility."""
    source_image: str
    extracted_text: str = ""
    mapped_text: str = ""
    cleaned_text: str = ""
    english: str = ""
    hindi: str = ""
    alternatives: List[str] = field(default_factory=list)
    notes: str = ""
    ocr_confidence: float = 0.0
    llm_confidence: float = 0.0

    @property
    def overall_confidence(self) -> float:
        ocr = max(0.0, min(1.0, self.ocr_confidence / 100.0))
        llm = max(0.0, min(1.0, self.llm_confidence))
        if ocr == 0 and llm == 0:
            return 0.0
        return round(0.4 * ocr + 0.6 * llm, 3)

    def pretty(self) -> str:
        return (
            f"=== Ancient Inscription Translation Report ===\n"
            f"Source        : {self.source_image}\n"
            f"Extracted     : {self.extracted_text}\n"
            f"Mapped        : {self.mapped_text}\n"
            f"Cleaned       : {self.cleaned_text}\n"
            f"English       : {self.english}\n"
            f"Hindi         : {self.hindi}\n"
            f"Alternatives  : {self.alternatives}\n"
            f"Notes         : {self.notes}\n"
            f"OCR conf      : {self.ocr_confidence:.1f}\n"
            f"LLM conf      : {self.llm_confidence:.2f}\n"
            f"Overall conf  : {self.overall_confidence:.2f}\n"
        )

    def as_dict(self) -> dict:
        d = asdict(self)
        d["overall_confidence"] = self.overall_confidence
        return d


# ---------------------------------------------------------------------------
# Image I/O (preserved from upstream EpiQ)
# ---------------------------------------------------------------------------

def load_image(path: str) -> np.ndarray:
    """Read an image with OpenCV, raising a helpful error on failure."""
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    img = cv2.imread(path, cv2.IMREAD_COLOR)
    if img is None:
        raise ValueError(f"OpenCV could not decode image: {path}")
    return img


def save_image(path: str, img: np.ndarray) -> None:
    """Save image, creating parent directories as needed."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    cv2.imwrite(path, img)


def image_hash(img: np.ndarray) -> str:
    """Return a short SHA-256 hex digest of the raw image bytes."""
    return hashlib.sha256(img.tobytes()).hexdigest()[:16]


# ---------------------------------------------------------------------------
# Structured logging setup
# ---------------------------------------------------------------------------

def setup_logging(
    level: str = "INFO",
    log_file: Optional[str] = None,
    fmt: str = "%(asctime)s %(levelname)s %(name)s: %(message)s",
) -> None:
    """
    Configure root logger with console + optional file handler.
    Call once at application startup.
    """
    handlers: List[logging.Handler] = [logging.StreamHandler()]
    if log_file:
        os.makedirs(os.path.dirname(os.path.abspath(log_file)), exist_ok=True)
        handlers.append(logging.FileHandler(log_file, encoding="utf-8"))
    logging.basicConfig(
        level=getattr(logging, level.upper(), logging.INFO),
        format=fmt,
        handlers=handlers,
    )


# ---------------------------------------------------------------------------
# Config loader (reads config/epirecover.yaml if available)
# ---------------------------------------------------------------------------

def load_config(config_path: Optional[str] = None) -> Dict:
    """
    Load YAML config. Returns an empty dict if pyyaml is not installed
    or the file does not exist — callers must supply sensible defaults.
    """
    path = config_path or os.environ.get(
        "EPIRECOVER_CONFIG",
        os.path.join(os.path.dirname(__file__), "config", "epirecover.yaml"),
    )
    try:
        import yaml
        if os.path.exists(path):
            with open(path, "r", encoding="utf-8") as f:
                return yaml.safe_load(f) or {}
    except ImportError:
        logging.getLogger(__name__).warning(
            "pyyaml not installed; skipping config file %s", path
        )
    except Exception as e:
        logging.getLogger(__name__).warning("Could not load config %s: %s", path, e)
    return {}
