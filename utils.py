# ---------------------------------------------------------------------------
# Provenance markers
# ---------------------------------------------------------------------------

class Provenance(str, Enum):
    """Source classification for every piece of text evidence."""
    OBSERVED         = "observed"         # directly read from image with high confidence
    OCR_PRED         = "ocr_predicted"    # OCR output, confidence may be low
    CORPUS           = "corpus_retrieved" # retrieved from an external inscription corpus
    CORPUS_RETRIEVED = "corpus_retrieved" # alias
    INFERRED         = "model_inferred"   # generated by an LLM or heuristic model
    MODEL_INFERRED   = "model_inferred"   # alias
    HUMAN            = "human_reviewed"   # accepted / edited by a human reviewer
    HUMAN_REVIEWED   = "human_reviewed"   # alias
    UNKNOWN          = "unknown"          # insufficient evidence; gap marker


# ---------------------------------------------------------------------------
# Candidate reconstruction unit
# ---------------------------------------------------------------------------

@dataclass
class ReconstructionCandidate:
    """
    A single candidate reading for a span of the inscription text.

    Fields are designed so every claim can be traced back to evidence.
    Do not set confidence to a high value without corresponding evidence.
    """
    candidate_text: str
    provenance: Provenance = Provenance.UNKNOWN
    candidate_id: str = ""
    affected_span: Optional[str] = None
    review_status: str = "pending"  # "pending", "accepted", "edited", "rejected"

    # Location within the inscription (token index, bounding box, or line)
    location_hint: Optional[str] = None

    # Supporting evidence references
    visual_evidence: Optional[str] = None    # description of image-level support
    corpus_evidence: Optional[str] = None    # matched corpus record ID(s)
    ocr_evidence: Optional[str] = None       # OCR engine output that supports this

    # Confidence: explicitly not a calibrated probability unless stated otherwise
    # Range [0, 1]; interpretation documented in EVALUATION_PROTOCOL.md
    confidence: float = 0.0
    confidence_note: str = "Heuristic estimate; not a calibrated probability."

    # Reasons for uncertainty in this candidate
    uncertainty_reasons: List[str] = field(default_factory=list)

    # Ranking score assigned by candidate_ranking module
    rank_score: float = 0.0
    rank_details: Dict[str, float] = field(default_factory=dict)

    def as_dict(self) -> Dict:
        d = asdict(self)
        d["provenance"] = self.provenance.value
        return d


# ---------------------------------------------------------------------------
# Extended report container
# ---------------------------------------------------------------------------

@dataclass
class RecoveryReport:
    """
    Full EpiRecover output for a single inscription image.

    Distinguishes:
      - Observed text (high-confidence OCR)
      - OCR hypotheses (engine output)
      - Corpus-retrieved evidence
      - Model-inferred candidates
      - Human-reviewed conclusions

    Keeps image restoration separate from text reconstruction.
    Generated/enhanced images must be labelled as visualizations only.
    """
    # --- Input metadata ---
    image_id: str = ""                    # hash of the original image
    image_hash: str = ""                  # SHA-256 fingerprint of input image
    request_id: str = ""                  # Unique request tracking identifier
    source_image: str = ""               # file name or path (not the raw bytes)
    inscription_id: Optional[str] = None
    script_hint: Optional[str] = None
    language_hint: Optional[str] = None
    historical_period: Optional[str] = None
    region: Optional[str] = None
    monument: Optional[str] = None
    dataset_source: Optional[str] = None
    researcher_notes: Optional[str] = None

    # --- Stage B: preprocessing ---
    preprocessing_stages: List[str] = field(default_factory=list)  # stage names applied

    # --- Stage C: damage analysis ---
    damage_method: str = "none"          # "heuristic" | "unet" | "none"
    damage_mask_path: Optional[str] = None
    damage_regions: List[Dict] = field(default_factory=list)  # [{x,y,w,h,severity}]
    damage_label: str = ""               # e.g. "HEURISTIC_BASELINE"

    # --- Stage D: OCR ---
    ocr_raw_text: str = ""
    ocr_engine: str = ""
    ocr_mean_confidence: float = 0.0
    ocr_boxes: List[Dict] = field(default_factory=list)  # [{text, conf, bbox}]
    ocr_script_hint: Optional[str] = None
    illegible_regions: List[str] = field(default_factory=list)  # [UNKNOWN] markers

    # --- Stage E: reconstruction candidates ---
    candidates: List[ReconstructionCandidate] = field(default_factory=list)
    top_candidate: Optional[ReconstructionCandidate] = None

    # Backward-compat fields from upstream EpiQ
    mapped_text: str = ""
    cleaned_text: str = ""
    english: str = ""
    hindi: str = ""
    alternatives: List[str] = field(default_factory=list)
    notes: str = ""
    llm_confidence: float = 0.0
    llm_backend: str = ""

    # --- Stage F: evidence retrieval ---
    retrieved_records: List[Dict] = field(default_factory=list)  # [{id, score, fields}]

    # --- Stage G: ranking & calibration ---
    ranking_weights: Dict[str, float] = field(default_factory=dict)
    ranking_validated: bool = False  # True only if weights were trained and validated
    should_abstain: bool = False
    abstention_reason: str = ""
    calibrated_confidence: float = 0.0
    fusion_features: Dict[str, float] = field(default_factory=dict)

    # --- Human review ---
    review_decision: Optional[str] = None    # "accepted" | "rejected" | "edited"
    reviewed_text: Optional[str] = None
    reviewer_id: Optional[str] = None

    # --- Aggregate confidence ---
    @property
    def overall_confidence(self) -> float:
        """Weighted blend; explicitly a heuristic estimate unless calibrated."""
        if self.calibrated_confidence > 0.0:
            return round(self.calibrated_confidence, 4)
        ocr = max(0.0, min(1.0, self.ocr_mean_confidence / 100.0))
        top_cand_conf = self.top_candidate.confidence if self.top_candidate else 0.0
        return round(0.5 * ocr + 0.5 * top_cand_conf, 3)

    def as_dict(self) -> Dict:
        d = asdict(self)
        d["overall_confidence"] = self.overall_confidence
        # Serialize provenance enum for candidates
        for c in d.get("candidates", []):
            if "provenance" in c and hasattr(c["provenance"], "value"):
                c["provenance"] = c["provenance"].value
        if d.get("top_candidate") and "provenance" in d["top_candidate"]:
            p = d["top_candidate"]["provenance"]
            if hasattr(p, "value"):
                d["top_candidate"]["provenance"] = p.value
        return d

    def to_json(self, indent: int = 2) -> str:
        return json.dumps(self.as_dict(), ensure_ascii=False, indent=indent)

    def pretty_summary(self) -> str:
        top_cand_str = "None"
        if self.top_candidate:
            top_cand_str = f"{self.top_candidate.candidate_text} (conf: {self.top_candidate.confidence:.2f}, prov: {self.top_candidate.provenance.value})"

        lines = [
            "===========================================================",
            "              EpiRecover Inscription Report                ",
            "===========================================================",
            f"Image ID         : {self.image_id}",
            f"Source           : {self.source_image}",
            f"Script Hint      : {self.script_hint or 'Not specified'}",
            f"Period / Region  : {self.historical_period or 'N/A'} / {self.region or 'N/A'}",
            f"Damage Analysis  : {self.damage_method} [{self.damage_label}]",
            f"OCR Engine       : {self.ocr_engine} (mean conf: {self.ocr_mean_confidence:.1f}%)",
            f"Raw OCR Output   : {self.ocr_raw_text or '[No text detected]'}",
            f"Dictionary Map   : {self.mapped_text or '[No matches]'}",
            f"Reconstructed    : {top_cand_str}",
            f"Candidates Count : {len(self.candidates)}",
            f"Corpus Evidence  : {len(self.retrieved_records)} records retrieved",
            f"English Meaning  : {self.english or '[Unavailable]'}",
            f"Hindi Meaning    : {self.hindi or '[Unavailable]'}",
            f"Overall Conf     : {self.overall_confidence:.2f} (heuristic estimate)",
            "-----------------------------------------------------------",
            "Integrity Note: Damage masks are heuristic baselines unless",
            "explicitly trained. Reconstructions retain provenance trace.",
            "===========================================================",
        ]
        return "\n".join(lines)


